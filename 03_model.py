"""
Stage 3 — The model: a modern (Llama-3 style) decoder-only transformer.

This file used to be a GPT-2 clone. It is now the architecture that every
current open model converges on, because each of these four changes is a strict
improvement at equal parameter count:

 RMSNorm                   LayerNorm without the mean-centring: same benefit,
                           fewer ops, no bias, and no mean to subtract before
                           the residual add. Norms are applied *before* each
                           sub-layer (pre-norm), which is what makes depth
                           trainable without hand-tuned warmup.
 RoPE                      Rotary position embeddings applied to q and k.
                           No position table at all: position enters the
                           attention logits as a *relative* rotation, which
                           generalises better past the training window than
                           GPT-2's learned absolute `wpe`.
 SwiGLU                    SiLU(x W_gate) * (x W_up) W_down instead of a GELU
                           MLP. Three matrices, hidden width 8/3*d_model to keep
                           FLOPs equal, better loss per parameter at small
                           scale.
 SDPA                      `F.scaled_dot_product_attention` for the attention
                           core: one call instead of (matmul + mask-add +
                           softmax + matmul). PyTorch dispatches it to a fused
                           CPU/CUDA kernel, and the causal mask is generated by
                           the kernel instead of being materialised, so memory
                           stops growing with T^2.
 separate q/k/v/o proj     Llama-3's layout, and the one that makes a KV cache
                           cheap to reason about (k/v are exactly what the
                           cache stores, nothing is shared with q).
 depth-scaled init         o_proj and down_proj start at
                           N(0, 0.02/sqrt(2*n_layer)) so the variance of the
                           residual stream does not grow with depth.
 tied embeddings           lm_head.weight is the token embedding matrix. Saves
                           vocab*d_model parameters (a third of this model) and
                           measurably helps at this scale.

What is deliberately NOT here: bias terms in the linear layers (they cancel in
the attention softmax and add nothing in the MLP), GPT-2's learned absolute
position embeddings, and the older per-head attention-logit bias.

KV cache + RoPE (the one part that is easy to get wrong)
-------------------------------------------------------
Cached k/v were *already rotated* when their token was processed, so a new
token must be rotated with *its own* absolute position, not position 0. This
module builds the RoPE table for positions [past, past+T) and slices it, and
the attention mask is chosen per case:
  * no cache (or empty cache)      -> is_causal=True, the kernel's own mask
  * one new token, non-empty cache -> no mask at all (attend to every past key)
  * T>1 against a non-empty cache  -> explicit bottom-right causal mask
The middle case matters: `is_causal=True` with q_len=1 would attend to the
*first* key only, which silently turns decoding into nonsense.
"""
from __future__ import annotations

import json
import math
from dataclasses import asdict, dataclass
from pathlib import Path

import torch
import torch.nn as nn
import torch.nn.functional as F

if not hasattr(F, "scaled_dot_product_attention"):          # pragma: no cover
    raise RuntimeError(
        "This model needs PyTorch >= 2.0 for F.scaled_dot_product_attention.\n"
        "Upgrade with:  python -m pip install -U torch"
    )


@dataclass
class GPTConfig:
    """Architecture hyperparameters. Saved next to every checkpoint.

    Named GPTConfig for backwards compatibility with the rest of the pipeline;
    the architecture it describes is Llama-3 style (see the module docstring).
    """
    vocab_size: int = 4096
    block_size: int = 256          # training context; RoPE extrapolates a bit beyond
    n_layer: int = 4
    n_head: int = 5
    d_model: int = 160
    dropout: float = 0.0           # 0.0 for large corpora; >0 only if overfitting
    rope_base: float = 10_000.0    # raise (1e5..5e5) to extend context beyond training
    rms_norm_eps: float = 1e-5     # Llama-3 value; the norm is computed in fp32

    @property
    def head_dim(self) -> int:
        assert self.d_model % self.n_head == 0, "d_model must divide by n_head"
        return self.d_model // self.n_head

    @property
    def mlp_hidden(self) -> int:
        """SwiGLU width: 8/3 * d_model (FLOPs-matched to a 4x GELU MLP), padded
        up to a multiple of 64 like Llama so the matrix is kernel-friendly."""
        return 64 * ((int(8 * self.d_model / 3) + 63) // 64)

    def save(self, path: str | Path) -> None:
        """Plain JSON, one canonical format. A checkpoint whose config cannot be
        parsed is a checkpoint you cannot read, so save() and load() must agree."""
        Path(path).write_text(json.dumps(asdict(self), indent=2))

    @classmethod
    def load(cls, path: str | Path) -> "GPTConfig":
        d = json.loads(Path(path).read_text())
        known = {f for f in cls.__dataclass_fields__}
        extra = set(d) - known
        if extra:                       # never silently drop a config key
            raise ValueError(f"unknown config keys {extra}; cannot reconstruct faithfully")
        return cls(**d)


