LlamaConfig = GPTConfig          # this is a Llama-style stack; both names work


# --------------------------------------------------------------------- layers
class RMSNorm(nn.Module):
    """x * rsqrt(mean(x^2) + eps) * weight — no mean subtraction, no bias."""

    def __init__(self, dim: int, eps: float = 1e-5):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(dim))
        self.eps = eps

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # fp32 math for stability: bf16 autocast would otherwise square a bf16
        # value, and (small)^2 is exactly where bf16 runs out of mantissa.
        norm = torch.rsqrt(x.float().pow(2).mean(-1, keepdim=True) + self.eps)
        return (x.float() * norm).type_as(x) * self.weight


def build_rope_cache(dim: int, seq_len: int, base: float, device, dtype):
    """(cos, sin) each [seq_len, dim]; `dim` is the head_dim.

    Llama's "half-split" layout: dimension i is rotated against i + dim/2. The
    frequencies are a geometric progression 1/base^(2i/dim), so low dimensions
    rotate fast (fine positional detail) and high dimensions rotate slowly.
    """
    inv = 1.0 / (base ** (torch.arange(0, dim, 2, device=device, dtype=torch.float32) / dim))
    t = torch.arange(seq_len, device=device, dtype=torch.float32)
    freqs = torch.outer(t, inv)                       # [T, dim/2]
    emb = torch.cat((freqs, freqs), dim=-1)           # [T, dim]
    return emb.cos().to(dtype), emb.sin().to(dtype)


def apply_rope(x: torch.Tensor, cos: torch.Tensor, sin: torch.Tensor) -> torch.Tensor:
    """x: [B, H, T, Dh]. Rotate each 2-D subspace by a position-dependent angle.

    Rotation preserves the norm, so this cannot change the scale of q or k —
    the property that makes RoPE safe to add to a deep residual stream.
    """
    d = x.shape[-1]
    x1, x2 = x[..., : d // 2], x[..., d // 2:]
    rot = torch.cat((-x2, x1), dim=-1)
    return x * cos + rot * sin


class Attention(nn.Module):
    """Multi-head causal self-attention with RoPE and SDPA."""

    def __init__(self, cfg: GPTConfig):
        super().__init__()
        self.n_head, self.head_dim = cfg.n_head, cfg.head_dim
        self.dropout = cfg.dropout
        self.q_proj = nn.Linear(cfg.d_model, cfg.d_model, bias=False)
        self.k_proj = nn.Linear(cfg.d_model, cfg.d_model, bias=False)
        self.v_proj = nn.Linear(cfg.d_model, cfg.d_model, bias=False)
        self.o_proj = nn.Linear(cfg.d_model, cfg.d_model, bias=False)

    def _split_heads(self, t: torch.Tensor, B: int, T: int) -> torch.Tensor:
        return t.view(B, T, self.n_head, self.head_dim).transpose(1, 2)

    def forward(self, x, cos, sin, kv_cache=None):
        B, T, D = x.shape

        q = self._split_heads(self.q_proj(x), B, T)
        k = self._split_heads(self.k_proj(x), B, T)
        v = self._split_heads(self.v_proj(x), B, T)

        # RoPE is applied to q and k only (never v): the rotation encodes
        # position into the *attention logits* q·k, which is where relative
        # position matters. cos/sin here already cover [past, past+T).
        q, k = apply_rope(q, cos, sin), apply_rope(k, cos, sin)

        past = 0
        if kv_cache is not None:      # incremental decoding: append to this layer's cache
            if kv_cache.new is not None:
                ck, cv = kv_cache.new
                past = ck.shape[2]
                k, v = torch.cat((ck, k), dim=2), torch.cat((cv, v), dim=2)
            kv_cache.new = (k, v)

        p = self.dropout if self.training else 0.0
        if past == 0:
            y = F.scaled_dot_product_attention(q, k, v, dropout_p=p, is_causal=True)
        elif T == 1:
            # A single new query must see *every* cached key. is_causal=True
            # would let it see only the first one (see the module docstring).
            y = F.scaled_dot_product_attention(q, k, v, dropout_p=p, is_causal=False)
        else:
            # Chunked prefill against a warm cache: causal, but shifted right by
            # `past` (a "bottom-right" causal mask), which SDPA cannot generate.
            idx_q = torch.arange(T, device=x.device).unsqueeze(1)
            idx_k = torch.arange(past + T, device=x.device).unsqueeze(0)
            mask = idx_k <= (idx_q + past)                 # bool: True = keep
            y = F.scaled_dot_product_attention(q, k, v, attn_mask=mask,
                                               dropout_p=p, is_causal=False)
        y = y.transpose(1, 2).reshape(B, T, D)
        return self.o_proj(y)


class MLP(nn.Module):
    """SwiGLU feed-forward: down(SiLU(gate(x)) * up(x))."""

    def __init__(self, cfg: GPTConfig):
        super().__init__()
        hidden = cfg.mlp_hidden
        self.gate_proj = nn.Linear(cfg.d_model, hidden, bias=False)
        self.up_proj = nn.Linear(cfg.d_model, hidden, bias=False)
        self.down_proj = nn.Linear(hidden, cfg.d_model, bias=False)
        self.drop = nn.Dropout(cfg.dropout)

    def forward(self, x):
        return self.drop(self.down_proj(F.silu(self.gate_proj(x)) * self.up_proj(x)))


class Block(nn.Module):
    """Pre-norm residual block: every sub-layer is a correction to the stream."""

    def __init__(self, cfg: GPTConfig):
        super().__init__()
        self.ln1 = RMSNorm(cfg.d_model, cfg.rms_norm_eps)
        self.attn = Attention(cfg)
        self.ln2 = RMSNorm(cfg.d_model, cfg.rms_norm_eps)
        self.mlp = MLP(cfg)

    def forward(self, x, cos, sin, kv_cache=None):
        x = x + self.attn(self.ln1(x), cos, sin, kv_cache)
        x = x + self.mlp(self.ln2(x))
        return x


class KVCacheSlot:
    """Per-layer cache holder: forward() fills .new with (k, v) covering every
    token seen so far in that layer. Append-only (no preallocation), so the
    same object works for any prompt length and batch size."""

    __slots__ = ("new",)

    def __init__(self):
        self.new = None


def make_kv_cache(n_layer: int) -> list[KVCacheSlot]:
    return [KVCacheSlot() for _ in range(n_layer)]


class Llama(nn.Module):
    """Decoder-only, Llama-3 style: RMSNorm + RoPE + SwiGLU + SDPA, pre-norm."""

    def __init__(self, cfg: GPTConfig):
        super().__init__()
        self.cfg = cfg
        self.wte = nn.Embedding(cfg.vocab_size, cfg.d_model)   # token embedding ("embed_tokens")
        self.blocks = nn.ModuleList([Block(cfg) for _ in range(cfg.n_layer)])
        self.ln_f = RMSNorm(cfg.d_model, cfg.rms_norm_eps)
        self.lm_head = nn.Linear(cfg.d_model, cfg.vocab_size, bias=False)
        self.lm_head.weight = self.wte.weight                  # tied embeddings
        self.drop = nn.Dropout(cfg.dropout)
        self.apply(self._init_weights)
        # Llama's depth-scaled init: the two projections that write back into the
        # residual stream get 1/sqrt(2*n_layer) so its variance stays ~O(1) with
        # depth. (GPT-2 used the same 1/sqrt(2*n_layer) after a zero-init.)
        scale = 1.0 / math.sqrt(2 * cfg.n_layer)
        for block in self.blocks:
            nn.init.normal_(block.attn.o_proj.weight, mean=0.0, std=0.02 * scale)
            nn.init.normal_(block.mlp.down_proj.weight, mean=0.0, std=0.02 * scale)

    def _init_weights(self, module: nn.Module) -> None:
        """GPT-2/Llama recipe: N(0, 0.02), no biases, unit norm gains.
        std=0.02 is not arbitrary — with tied embeddings it makes E[logit] ~ 0,
        which puts the initial cross-entropy within a hair of ln(V), the loss of
        a uniform model."""
        if isinstance(module, nn.Linear):
            nn.init.normal_(module.weight, mean=0.0, std=0.02)
            if module.bias is not None:
                nn.init.zeros_(module.bias)
        elif isinstance(module, nn.Embedding):
            nn.init.normal_(module.weight, mean=0.0, std=0.02)
        elif isinstance(module, RMSNorm):
            nn.init.ones_(module.weight)

    @property
    def n_layer(self) -> int:
        return self.cfg.n_layer

    # ---------------------------------------------------------------- forward
    def forward(self, idx, targets=None, kv_cache=None):
        """idx: [B, T] token ids. kv_cache: list of KVCacheSlot (one per layer),
        or None. Returns (logits [B, T, V], loss or None)."""
        B, T = idx.shape
        past = 0
        if kv_cache is not None and kv_cache[0].new is not None:
            past = kv_cache[0].new[0].shape[2]
        x = self.drop(self.wte(idx))
        # RoPE for positions [past, past+T): cached k/v keep the rotation they
        # were created with, so only the new tokens may be rotated.
        cos, sin = build_rope_cache(self.cfg.head_dim, past + T, self.cfg.rope_base,
                                    x.device, torch.float32)
        cos, sin = cos[past:past + T][None, None], sin[past:past + T][None, None]
        for i, block in enumerate(self.blocks):
            x = block(x, cos, sin, None if kv_cache is None else kv_cache[i])
        logits = self.lm_head(self.ln_f(x))
        loss = None
        if targets is not None:
            # -100 is PyTorch's conventional ignore index. Pretraining blocks have
            # no padding, while SFT uses it both for padding and for user/prompt
            # tokens so gradients come only from assistant responses.
            loss = F.cross_entropy(logits.reshape(-1, logits.size(-1)),
                                   targets.reshape(-1), ignore_index=-100)
        return logits, loss

    # ------------------------------------------------------------- param groups
    def configure_optimizers(self, weight_decay, lr, betas):
        """AdamW with no decay on 1-D params (norms) and biases. Also reports
        how much of the parameter budget actually receives decay."""
        decay, nodecay = [], []
        for _, p in self.named_parameters():
            if not p.requires_grad:
                continue
            (decay if p.dim() >= 2 else nodecay).append(p)
        params = [{"params": decay, "weight_decay": weight_decay},
                  {"params": nodecay, "weight_decay": 0.0}]
        n_decay = sum(p.numel() for p in decay)
        total = n_decay + sum(p.numel() for p in nodecay)
        print(f"[opt] {n_decay:,}/{total:,} params get weight decay "
              f"({100*n_decay/total:.1f}%)")
        return torch.optim.AdamW(params, lr=lr, betas=betas)

    # ----------------------------------------------------------------- helpers
    @torch.no_grad()
    def estimate_flops(self, block_size: int) -> int:
        """Forward-pass FLOPs for one sequence, multiply-adds counted as 2.
        = 2 * (non-embedding params) * T, i.e. the matmul cost through every layer,
        plus the quadratic attention term. 6ND for train (fwd + bwd) is 3x this.
        Excludes the embedding lookup, which is a gather, not a matmul."""
        nparams = self.num_params(exclude_embeddings=True)
        fwd = 2 * nparams * block_size
        attn = 0
        for _ in self.blocks:
            attn += 2 * 2 * block_size * block_size * self.cfg.d_model
        return fwd + attn

    def num_params(self, exclude_embeddings: bool = False) -> int:
        emb = self.wte.weight.numel()
        tot = sum(p.numel() for p in self.parameters())
        return tot - emb if exclude_embeddings else tot

    @torch.no_grad()
    def get_lr(self, it: int, max_iters: int, lr: float, min_lr_frac: float, warmup: int) -> float:
        """Linear warmup -> cosine decay to min_lr_frac * lr. Warmup prevents
        early AdamW second-moment blowups; the cosine tail extracts the last few
        percent of loss for free. pct saturates at 1, so past max_iters the rate
        simply stays at its floor."""
        if it < warmup:
            return lr * (it + 1) / warmup
        pct = min(1.0, (it - warmup) / max(1, max_iters - warmup))
        f = (1 + math.cos(math.pi * pct)) / 2
        return lr * (min_lr_frac + (1 - min_lr_frac) * f)

    def save(self, path: str | Path) -> None:
        path = Path(path); path.mkdir(parents=True, exist_ok=True)
        torch.save(self.state_dict(), path / "model.pt")
        Path(path, "config.txt").write_text(json.dumps(asdict(self.cfg), indent=2))

    @classmethod
    def load(cls, path: str | Path, device="cpu") -> "Llama":
        cfg = GPTConfig.load(Path(path) / "config.txt")
        model = cls(cfg).to(device)
        sd = torch.load(Path(path) / "model.pt", map_location=device, weights_only=True)
        model.load_state_dict(sd)
        return model.eval()


GPT = Llama          # the pipeline's historical name for "the model"


# ------------------------------------------------------------------ unit tests
if __name__ == "__main__":
    torch.manual_seed(0)
    cfg = GPTConfig(vocab_size=512, block_size=32, n_layer=3, n_head=4, d_model=64)
    model = GPT(cfg)
    x = torch.randint(0, cfg.vocab_size, (2, 32))
    y = torch.randint(0, cfg.vocab_size, (2, 32))

    logits, loss = model(x, y)
    assert logits.shape == (2, 32, 512)
    print(f"[model] params={model.num_params():,}  init loss={loss.item():.3f} "
          f"vs ln(V)={math.log(cfg.vocab_size):.3f}")
    # invariant: an untrained model should start ~ at the entropy of the uniform
    # distribution over the vocab. Being far above it means the head is mis-scaled.
    assert abs(loss.item() - math.log(cfg.vocab_size)) < 0.35, "init loss is wrong"

    # invariant: causality — changing token t must not change logits[:t].
    x2 = x.clone(); x2[:, 20:] = torch.randint(0, cfg.vocab_size, (2, 12))
    l1, _ = model(x); l2, _ = model(x2)
    assert torch.allclose(l1[:, :20], l2[:, :20], atol=1e-5), "attention is not causal!"
    print("[model] causality test passed (future tokens cannot leak into the past)")

    # invariant: RoPE is relative — shifting q and k by the same offset leaves
    # the attention logits (and therefore the output) unchanged.
    with torch.no_grad():
        head_dim = cfg.head_dim
        cos, sin = build_rope_cache(head_dim, 64, cfg.rope_base, "cpu", torch.float32)
        q = torch.randn(1, cfg.n_head, 1, head_dim)
        k = torch.randn(1, cfg.n_head, 4, head_dim)
        shift = 7
        same = (apply_rope(q, cos[shift:shift+1], sin[shift:shift+1])
                @ apply_rope(k, cos[shift+4:shift+8], sin[shift+4:shift+8]).transpose(-1, -2))
        base = (apply_rope(q, cos[:1], sin[:1]) @ apply_rope(k, cos[4:8], sin[4:8]).transpose(-1, -2))
    err_rel = (same - base).abs().max().item()
    print(f"[model] RoPE relative-position invariance: max abs diff = {err_rel:.2e}")
    assert err_rel < 1e-5, "RoPE is not relative"

    # invariant: SDPA implementation == explicit masked softmax attention
    with torch.no_grad():
        att = model.blocks[0].attn
        h = torch.randn(2, 32, cfg.d_model)
        cos1, sin1 = build_rope_cache(head_dim, 32, cfg.rope_base, "cpu", torch.float32)
        cos1, sin1 = cos1[None, None], sin1[None, None]
        got = att(h, cos1, sin1)
        # reference: same projections, same RoPE, explicit causal softmax
        B, T, D = h.shape
        q = apply_rope(att._split_heads(att.q_proj(h), B, T), cos1, sin1)
        k = apply_rope(att._split_heads(att.k_proj(h), B, T), cos1, sin1)
        v = att._split_heads(att.v_proj(h), B, T)
        scores = q @ k.transpose(-2, -1) / math.sqrt(att.head_dim)
        mask = torch.triu(torch.ones(T, T, dtype=torch.bool), diagonal=1)
        scores = scores.masked_fill(mask, float("-inf"))
        ref = ((scores.softmax(-1) @ v).transpose(1, 2).reshape(B, T, D))
        ref = att.o_proj(ref)
    err = (got - ref).abs().max().item()
    print(f"[model] SDPA vs explicit attention: max abs diff = {err:.2e}")
    assert err < 1e-5, f"SDPA path disagrees with the reference: {err}"

    # invariant: KV-cached incremental decoding must equal a full forward pass
    with torch.no_grad():
        ref, _ = model(x)                       # full-sequence logits
        ref_last = ref[:, -1]
        # (a) feed the whole prefix, capturing k/v for each layer.
        #     NOTE: forward() *mutates* the slots, so snapshot before reuse.
        slots = make_kv_cache(cfg.n_layer)
        _, _ = model(x[:, :-1], kv_cache=slots)
        snap = [sl.new for sl in slots]
        # (b) feed ONLY the final token against a fresh copy of that cache
        for sl, c in zip(slots, snap):
            sl.new = (c[0].clone(), c[1].clone()) if c is not None else None
        got, _ = model(x[:, -1:], kv_cache=slots)
        err = (got[:, -1] - ref_last).abs().max().item()
        print(f"[model] KV-cache vs full forward (1 token): max abs diff = {err:.2e}")
        assert err < 2e-4, f"KV cache mismatch: {err}"

        # (c) chunked prefill: [0:20) then [20:32) must equal one 32-token pass
        slots = make_kv_cache(cfg.n_layer)
        _, _ = model(x[:, :20], kv_cache=slots)
        chunked, _ = model(x[:, 20:], kv_cache=slots)
        err = (chunked - ref[:, 20:]).abs().max().item()
        print(f"[model] chunked prefill vs full forward: max abs diff = {err:.2e}")
        assert err < 2e-4, f"chunked prefill mismatch: {err}"
    print("[model] all invariants hold")
